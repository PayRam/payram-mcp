#!/usr/bin/env node
/**
 * Generates src/generated/buildInfo.ts — the single source of the server
 * version and of repo documents that tools serve at runtime.
 *
 * Why generated instead of read with fs at runtime: Vercel's file tracer
 * cannot see paths built at runtime, so docs/PAYRAM_AGENT_ONBOARDING.md was
 * missing from the deployed bundle (onboard_agent_setup → ENOENT). Inlining
 * the text makes the bundle self-contained.
 *
 * Run by prebuild/predev/pretest; the output is committed and CI checks it
 * is up to date (`git diff --exit-code src/generated`).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const onboarding = readFileSync(path.join(root, 'docs/PAYRAM_AGENT_ONBOARDING.md'), 'utf8');

const out = `// GENERATED by scripts/generate-build-info.mjs — do not edit by hand.
// Source: package.json (version), docs/PAYRAM_AGENT_ONBOARDING.md.

export const MCP_SERVER_VERSION = ${JSON.stringify(pkg.version)};

export const MCP_REGISTRY_NAME = ${JSON.stringify(pkg.mcpName)};

export const AGENT_ONBOARDING_MD = ${JSON.stringify(onboarding)};
`;

const target = path.join(root, 'src/generated/buildInfo.ts');
mkdirSync(path.dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`[build-info] wrote ${path.relative(root, target)} (v${pkg.version})`);

// Keep the version in the discovery documents in step with package.json.
const syncVersion = (file, set) => {
  const full = path.join(root, file);
  const doc = JSON.parse(readFileSync(full, 'utf8'));
  set(doc);
  writeFileSync(full, `${JSON.stringify(doc, null, 2)}\n`);
};
syncVersion('server.json', (doc) => {
  doc.version = pkg.version;
});
syncVersion('public/.well-known/mcp/server-card.json', (doc) => {
  doc.serverInfo.version = pkg.version;
});
